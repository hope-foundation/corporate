/**
 * จุดขึ้นบรรทัดใหม่สำหรับข้อความภาษาไทย
 *
 * ปัญหา: Chrome ตัดบรรทัดภาษาไทยด้วยพจนานุกรม ICU ซึ่ง "ตัดได้" ก็จริง
 * แต่พจนานุกรมไม่รู้จักคำทับศัพท์อย่าง "คริสตจักร" จึงซอยเป็น "ค|ริ|สต|จักร"
 * ผลคือบนมือถือได้บรรทัดว่า "ตามห้องประชุมที่คริ / สตจักรเช่า" ผ่ากลางชื่อ
 * (Node ก็ใช้ ICU ตัวเดียวกัน — `Intl.Segmenter("th")` ให้ผลพังเหมือนกันเป๊ะ)
 *
 * ⚠️ สิ่งที่ทดสอบแล้วว่า "ไม่ช่วย":
 *   - `overflow-wrap: break-word | normal | anywhere` — ได้บรรทัดเหมือนกันทั้งสามค่า
 *     เพราะตัวที่ตัดคือพจนานุกรมของ Chrome ไม่ใช่ overflow-wrap
 *   - ใส่ `<wbr>` เฉย ๆ — `<wbr>` แค่ "เพิ่ม" จุดที่ตัดได้ ห้ามจุดเดิมของ Chrome ไม่ได้
 *
 * วิธีที่ใช้จริง: ห่อคำที่ห้ามตัดด้วย `white-space: nowrap` (class `.nb`)
 * แล้วเปิดจุดตัดเองด้วย `<wbr>` ระหว่างคำ → ตัดได้เฉพาะจุดที่เรากำหนดเท่านั้น
 *
 * ในข้อความที่ src/data/site.ts ใช้ "|" คั่นคำ มองเห็นได้ แก้ได้ ตรวจทานได้
 * ไม่ใช่อักขระล่องหนแบบ zero-width space ที่หลุดไปกับการ copy/paste
 *
 * ⚠️ ห้ามใส่ "|" กลางชื่อเฉพาะ โดยเฉพาะ "ความหวัง" ในชื่อคริสตจักร/มูลนิธิ
 * ⚠️ ช่องว่างจริงในข้อความยังเป็นจุดตัดตามปกติ — จงใจปล่อยไว้นอก `.nb`
 */

const ESCAPES: Record<string, string> = {
  "&": "&amp;",
  "<": "&lt;",
  ">": "&gt;",
  '"': "&quot;",
  "'": "&#39;",
};

const escapeHtml = (s: string) => s.replace(/[&<>"']/g, (c) => ESCAPES[c]!);

/** ข้อความล้วน ไม่มีเครื่องหมาย — ใช้กับ <title>, meta description, alt, JSON-LD */
export const plain = (s: string): string => s.replaceAll("|", "");

/**
 * ข้อความที่ตัดบรรทัดได้เฉพาะตรง "|" และตรงช่องว่างเท่านั้น — ใช้กับ set:html
 * escape ก่อนเสมอ เพราะผลลัพธ์ถูกแทรกเป็น HTML ดิบ
 */
export const withBreaks = (s: string): string =>
  s
    .split("|")
    .map((token) =>
      token
        // เก็บช่องว่างไว้ "นอก" span เพื่อให้ยังเป็นจุดตัดได้ตามปกติ
        .split(/( +)/)
        .map((part) => (part.trim() === "" ? part : `<span class="nb">${escapeHtml(part)}</span>`))
        .join(""),
    )
    .join("<wbr>");
